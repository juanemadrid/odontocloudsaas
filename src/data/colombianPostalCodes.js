/**
 * Normaliza un string para búsqueda insensible a acentos y mayúsculas
 */
const normalizeText = (text) => {
  return String(text || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();
};

/**
 * Obtiene el código postal oficial colombiano a partir del nombre de la ciudad / municipio
 * @param {string} cityName - Nombre del municipio o ciudad
 * @returns {string} Código postal de 6 dígitos o vacío si no se encuentra
 */
export const getPostalCodeForCity = (cityName) => {
  if (!cityName) return "";
  const key = normalizeText(cityName);

  // Coincidencia directa
  if (COLOMBIAN_POSTAL_CODES[key]) {
    return COLOMBIAN_POSTAL_CODES[key];
  }

  // Buscar si la clave está contenida o contiene el nombre
  for (const [k, code] of Object.entries(COLOMBIAN_POSTAL_CODES)) {
    if (k.length >= 4 && (key === k || key.startsWith(k) || k.startsWith(key))) {
      return code;
    }
  }

  return "";
};
